-- キー集合の確認（チェックサム的な集計）
SELECT
    'REGIONS' AS TABLE_NAME,
    SUM(REGION_ID) AS KEY_SUM,
    MIN(REGION_ID) AS KEY_MIN,
    MAX(REGION_ID) AS KEY_MAX,
    COUNT(*) AS ROW_COUNT
FROM SRC_SCHEMA.REGIONS
UNION ALL
SELECT
    'CUSTOMERS',
    SUM(CUSTOMER_ID),
    MIN(CUSTOMER_ID),
    MAX(CUSTOMER_ID),
    COUNT(*)
FROM SRC_SCHEMA.CUSTOMERS
UNION ALL
SELECT
    'ORDERS',
    SUM(ORDER_ID),
    MIN(ORDER_ID),
    MAX(ORDER_ID),
    COUNT(*)
FROM SRC_SCHEMA.ORDERS;
