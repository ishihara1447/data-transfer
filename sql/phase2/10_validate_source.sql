-- Phase 2: 移行元（SRC_SCHEMA）の検証値取得
-- 実行場所: oracle-src コンテナ内（SYSDBA 接続 + ALTER SESSION SET CONTAINER=XEPDB1）
-- 注意: データジェネレータが稼働中の場合、現在件数は Export 時より多い
--       AS OF SCN を使用して基準SCN断面の件数を取得すること
-- 使い方: BASELINE_SCN を :scn にバインドして実行
-- 本番では別途確認が必要な項目:
--   BLOB/CLOB のハッシュ比較（今回の対象テーブルにはLOBなし）
--   UNDO_RETENTION が短い場合は AS OF SCN 取得が失敗する可能性あり

-- 件数確認（AS OF SCN を使用）
-- ※ :scn に BASELINE_SCN の値を設定すること
SELECT 'SRC_SCHEMA' AS SCHEMA_NAME, 'REGIONS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
FROM SRC_SCHEMA.REGIONS AS OF SCN :scn
UNION ALL
SELECT 'SRC_SCHEMA', 'CUSTOMERS', COUNT(*) FROM SRC_SCHEMA.CUSTOMERS AS OF SCN :scn
UNION ALL
SELECT 'SRC_SCHEMA', 'ORDERS', COUNT(*) FROM SRC_SCHEMA.ORDERS AS OF SCN :scn;

